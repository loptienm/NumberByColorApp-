private fun pal(vararg entries: Pair<Int, String>): Map<Int, Int> =
  entries.associate { (k, v) -> k to hexToArgb(v) }

private fun animTpl(
  id: String,
  title: String,
  gridWidth: Int,
  gridHeight: Int,
  palette: Map<Int, Int>,
  frameMs: Int,
  frames: List<List<String>>,
): PictureTemplate =
  PictureTemplate(
    id = id,
    title = title,
    gridWidth = gridWidth,
    gridHeight = gridHeight,
    palette = palette,
    grid = frames.first(),
    frames = frames,
    frameMs = frameMs,
    still = palette.keys.toList(),
  )

